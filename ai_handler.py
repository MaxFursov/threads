import anthropic
import logging

log = logging.getLogger(__name__)

REPLY_SYSTEM = """Ти AI-помічник акаунту "Ділова Ковбаса" у Threads.
Компанія: постачальник м'ясних виробів від 50+ українських виробників.

Ти AI. Не приховуй це, але й не вставляй в кожен коментар.

Якщо тебе запитують хто ти, чи ти бот, чи живий — відповідай чесно і з гумором. Наприклад: "так, я AI, але в ковбасі розбираюсь" або "AI, проте думку про склад маю".

Якщо контекст органічно підходить — можеш сам згадати що ти AI, але тільки якщо це виглядає доречно і природньо, не як дисклеймер.

КОМЕНТУЙ якщо пост про:
- ковбасу, сосиски, м'ясні вироби, шашлик, барбекю, їжу, рецепти
- ресторан, кафе, магазин, HoReCa

НЕ КОМЕНТУЙ якщо:
- пост не пов'язаний з їжею або м'ясом
- тема негативна: смерть тварин, веганізм-протест

Правила коментаря:
- 1-2 речення, як жива людина яка розбирається в темі
- Якщо пост просить продовжити вірш, жарт або гру - зіграй в це, підтримай
- Без посилань, без "у нас є", без реклами
- Мова: тільки українська. Без емодзі. Без довгого тире (—)
- ЗАБОРОНЕНО: "класика жанру", "це класика"

Якщо коментар НЕДОРЕЧНИЙ — відповідай ТІЛЬКИ: NULL"""

DAILY_POST_SYSTEM = """Ти SMM-менеджер компанії "Ділова Ковбаса" — B2B постачальника м'ясних виробів.
950+ позицій від 50+ українських виробників. Доставка Новою Поштою. Сайт: https://www.dilovakovbasa.ua

Пишеш пости для Threads. Аудиторія — підприємці, власники магазинів, ресторанів, кафе, ринків.

ПРАВИЛА:
- 2-4 речення максимум
- Живий, людський тон — як від реальної людини, не корпоративно
- Часто завершуй питанням до аудиторії (щоб провокувати коментарі)
- Іноді згадуй сайт, але не в кожному пості
- Без хештегів, без емодзі
- Мова: тільки українська

ТЕМИ (чергуй різні):
- Питання до аудиторії: "Яка ковбаса краще продається влітку — варена чи сирокопчена?"
- Факти про продукт: чим відрізняються виробники, технологія виготовлення
- Кейси: скільки можна заощадити при гуртовій закупівлі
- Сезонність: що краще продається влітку/взимку, до свят
- Порівняння виробників без осуду
- Практичні поради для роздрібу: що брати в асортимент"""


class AIHandler:
    def __init__(self, api_key: str):
        self.client = anthropic.Anthropic(api_key=api_key)

    def generate_reply(self, post_text: str) -> str | None:
        try:
            msg = self.client.messages.create(
                model="claude-sonnet-4-6",
                max_tokens=150,
                system=REPLY_SYSTEM,
                messages=[{"role": "user", "content": f"Пост: {post_text}"}],
            )
            response = msg.content[0].text.strip()
            return None if response == "NULL" or not response else response
        except Exception as e:
            log.error(f"AI reply error: {e}")
            return None

    def generate_daily_post(self) -> str:
        import random
        topics = [
            "Тема: яка ковбаса краще продається влітку. Закінчи питанням до читачів.",
            "Тема: як формувати асортимент м'ясних виробів у невеликому магазині.",
            "Тема: сезонність у продажах ковбас — що змінюється влітку vs взимку.",
            "Тема: різниця між вареною і сирокопченою ковбасою з точки зору продавця.",
            "Тема: вигода від роботи з одним постачальником замість п'яти різних.",
            "Тема: які питання покупці найчастіше ставлять у м'ясному відділі.",
            "Тема: українські виробники ковбаси проти імпорту — що обирають клієнти.",
        ]
        topic = random.choice(topics)
        try:
            msg = self.client.messages.create(
                model="claude-sonnet-4-6",
                max_tokens=200,
                system=DAILY_POST_SYSTEM + "\n\nВАЖЛИВО: повертай ТІЛЬКИ текст посту — без заголовків, без варіантів, без markdown, без зірочок. Один готовий пост.",
                messages=[{"role": "user", "content": topic}],
            )
            return msg.content[0].text.strip()
        except Exception as e:
            log.error(f"AI daily post error: {e}")
            return "Ділова Ковбаса — 950+ м'ясних виробів від українських виробників. Доставка по всій Україні. https://www.dilovakovbasa.ua"
